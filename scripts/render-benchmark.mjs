#!/usr/bin/env node
// Renders every published planted-defect-benchmark claim from one owner:
// `benchmark/results/latest.json` (#270, SPEC 2.0 §8.2).
//
//   node scripts/render-benchmark.mjs          # write the rendered blocks
//   node scripts/check-benchmark-claims.mjs    # fail CI when they drift
//
// Targets are the three `<!-- BEGIN benchmark-score -->` blocks and the
// generated TypeScript module the site imports. A number that appears in
// prose and nowhere else is a number nobody can re-derive; every one of them
// is substituted here, from the result file, or it is not published.
//
// `readLatest()` is also where a result file is refused: a dry run (a fake
// reviewer's score is not a measurement), a partial suite (a smaller corpus
// under the same headline), a scenario set that is not the committed corpus,
// totals its own scenarios do not add up to, and a run that scored nothing on
// one side of the corpus. It is the only door into the published blocks, so
// it is the only place those refusals have to live.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const LATEST = join(ROOT, 'benchmark', 'results', 'latest.json');
const SCENARIOS = join(ROOT, 'benchmark', 'scenarios');

const BEGIN = '<!-- BEGIN benchmark-score -->';
const END = '<!-- END benchmark-score -->';
const JSX_BEGIN = '{/* BEGIN benchmark-score */}';
const JSX_END = '{/* END benchmark-score */}';

const GENERATED_NOTE =
  '<!-- Generated by scripts/render-benchmark.mjs from benchmark/results/latest.json. Do not edit by hand. -->';

export const MARKDOWN_TARGETS = [
  join(ROOT, 'benchmark', 'RESULTS.md'),
  join(ROOT, 'benchmark', 'README.md'),
  join(ROOT, 'README.md'),
];
export const SITE_CONST = join(ROOT, 'site', 'lib', 'benchmark-score.ts');
export const JSX_TARGETS = [
  join(ROOT, 'site', 'app', 'page.tsx'),
  join(ROOT, 'site', 'app', 'docs', 'multi-pass', 'page.tsx'),
];

/**
 * The totals the per-defect table supports, counted the way the scorer counts.
 *
 * `src/core/benchmark-score.ts` owns the rules; this is the cross-check the
 * published file is held to, and test/benchmark-claims.test.js runs the two
 * against the same scored run so they cannot drift apart. A result file can be
 * hand-written — this one is — so a headline nothing re-derives is a headline
 * nobody can refute.
 */
export function derivedTotals(scenarios) {
  const count = (expected, verdict) =>
    scenarios.filter((s) => s.expected === expected && s.verdict === verdict).length;
  const scored = (expected) => scenarios.filter((s) => s.expected === expected && s.verdict !== 'unverified').length;
  const pct = (numerator, denominator) =>
    denominator <= 0 ? 0 : Math.round((numerator / denominator) * 1000) / 10;

  const caught = count('finding', 'caught');
  const falsePositives = count('clean', 'false-positive');
  return {
    caught,
    total: scored('finding'),
    decoysClean: count('clean', 'caught'),
    decoysTotal: scored('clean'),
    falsePositives,
    unverified: scenarios.filter((s) => s.verdict === 'unverified').length,
    recallPct: pct(caught, scored('finding')),
    precisionPct: pct(caught, caught + falsePositives),
  };
}

/**
 * The corpus on disk: one entry per committed answer key.
 *
 * `config.suite: 'all'` is a label a result file writes about itself, so it
 * cannot be what proves the run covered the corpus. The answer keys can.
 */
export function committedCorpus(dir = SCENARIOS) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => JSON.parse(readFileSync(join(dir, e.name, 'answer.json'), 'utf8')))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

export function readLatest(path = LATEST) {
  const result = JSON.parse(readFileSync(path, 'utf8'));
  if (result.dryRun) {
    throw new Error(
      `${path} is a dry run (dryRun: true) — a fake reviewer's score is not a measurement and is not publishable`,
    );
  }
  if (result.config?.suite !== 'all') {
    // A subset scored fewer scenarios and left the rest out of the counts
    // rather than unverified, so the sentence would report a shrunken corpus
    // with no remainder named. A cost-stopped full run still records `all`
    // and carries its remainder as `unverified`, so that stays publishable.
    throw new Error(
      `${path} scored --suite ${JSON.stringify(result.config?.suite)} — a partial suite is not the published score`,
    );
  }

  // Against the keys on disk, not against the file's own label: a result that
  // dropped the six decoys still said `suite: all`, and its headline rendered
  // over fourteen scenarios as though that were the corpus.
  const scored = new Map((result.scenarios ?? []).map((s) => [s.id, s]));
  const corpus = committedCorpus();
  const corpusProblems = [];
  // Counted over the array, not the map above: a Map keyed by id dedupes in
  // silence, so membership held in both directions while nine extra copies of
  // an already-caught scenario rode along and lifted the headline past the
  // corpus. The published counts are over `scenarios`, so the multiset is what
  // has to equal the corpus, not the set.
  const seen = new Set();
  for (const entry of result.scenarios ?? []) {
    if (seen.has(entry.id)) corpusProblems.push(`${entry.id} is scored twice`);
    seen.add(entry.id);
  }
  for (const key of corpus) {
    const entry = scored.get(key.id);
    if (!entry) corpusProblems.push(`${key.id} is missing`);
    else if (entry.expected !== key.expected) {
      corpusProblems.push(`${key.id} is scored as ${JSON.stringify(entry.expected)}, the key says ${JSON.stringify(key.expected)}`);
    }
  }
  for (const id of scored.keys()) {
    if (!corpus.some((key) => key.id === id)) corpusProblems.push(`${id} is not in the committed corpus`);
  }
  if (corpusProblems.length > 0) {
    throw new Error(
      `${path} does not score the committed corpus (${corpusProblems.join('; ')}) ` +
        `— the headline names ${corpus.length} scenarios, so it has to have been scored over them`,
    );
  }

  const derived = derivedTotals(result.scenarios ?? []);
  const disagreement = Object.keys(derived).filter((field) => result.totals?.[field] !== derived[field]);
  if (disagreement.length > 0) {
    throw new Error(
      `${path} totals disagree with its own scenarios ` +
        `(${disagreement.map((f) => `${f}: ${result.totals?.[f]} published, ${derived[f]} scored`).join(', ')}) ` +
        `— a published score has to be re-derivable from the per-defect table`,
    );
  }

  // A ratio over nothing is not a small measurement, it is none: a revoked key
  // left every scenario unverified and published "caught 0/0 (0%)", which
  // reads as a reviewer that failed rather than as a run that never happened.
  // Precision over no decoys is 100% by arithmetic whatever the reviewer did.
  if (derived.total === 0) {
    throw new Error(
      `${path} scored no planted defect at all (${derived.unverified} unverified of ${result.scenarios.length}) ` +
        `— there is no recall to publish, only a run that did not happen`,
    );
  }
  if (derived.decoysTotal === 0) {
    throw new Error(
      `${path} scored no clean decoy (${derived.unverified} unverified of ${result.scenarios.length}) ` +
        `— precision over zero decoys is 100% by arithmetic, not by review`,
    );
  }
  return result;
}

/**
 * The remainder, as one sentence, or '' when there is none.
 *
 * Every published block writes its own prose around these numbers, so the
 * remainder has to be a fact a block can render like any other — the front
 * page could only interpolate `caught`/`planted`, and so published "100%
 * recall" for a run that reached eight scenarios of twenty. §2.8: whenever a
 * tool elides content it MUST leave a marker at the cut saying how much.
 */
export function unverifiedClause(unverified) {
  if (!unverified) return '';
  return (
    `${unverified} scenario${unverified === 1 ? '' : 's'} went unscored and ` +
    `${unverified === 1 ? 'is' : 'are'} reported unverified, never clean.`
  );
}

/** The fields the published wording is built from. */
export function benchmarkFacts(result) {
  const t = result.totals;
  const c = result.config;
  return {
    scenarios: result.scenarios.length,
    // What the CORPUS holds, as against what the run scored. readLatest has
    // already held `result.scenarios` to the committed keys, one entry each,
    // so these are the keys on disk counted — and they do not move when a run
    // stops early. `planted`/`decoys` below are the sample: a run stopped at
    // three scenarios published the fixed public corpus as holding two planted
    // defects and one decoy, because one clause read the sample as the corpus.
    corpusPlanted: result.scenarios.filter((s) => s.expected === 'finding').length,
    corpusDecoys: result.scenarios.filter((s) => s.expected === 'clean').length,
    planted: t.total,
    caught: t.caught,
    recallPct: t.recallPct,
    decoys: t.decoysTotal,
    decoysClean: t.decoysClean,
    falsePositives: t.falsePositives,
    precisionPct: t.precisionPct,
    unverified: t.unverified,
    unverifiedClause: unverifiedClause(t.unverified),
    reviewersPerScenario: c.reviewersPerScenario,
    // Phrased here because the site blocks may not carry a numeral, and
    // "1 independent reviewers" is what the automated run renders otherwise.
    reviewersPhrase: `${c.reviewersPerScenario} independent reviewer${c.reviewersPerScenario === 1 ? '' : 's'}`,
    model: c.reviewerModel ?? 'model unrecorded',
    effort: c.reviewerEffort ?? 'unrecorded',
    recipeSha: c.recipeSha256 ? c.recipeSha256.slice(0, 12) : 'unrecorded',
    invocation: c.invocation,
    runDate: String(result.startedAt).slice(0, 10),
    costLine:
      typeof result.cost.spentUsd === 'number' && typeof result.cost.capUsd === 'number'
        ? `${result.cost.spendEstimated ? 'about ' : ''}$${result.cost.spentUsd.toFixed(2)} of a $${result.cost.capUsd.toFixed(2)} cap`
        : 'spend not metered',
    // Self-clearing: a run that recorded no recipe hash cannot be attributed
    // to the recipe shipping today, so it is published with that said. The
    // first automated run carries a hash and the caveat empties itself.
    caveat: c.recipeSha256
      ? ''
      : 'The recipe that produced this score was not recorded, so it cannot be matched to the one ' +
        'shipping today — read it as a historical measurement, not a reproducible claim.',
  };
}

/**
 * The published wording. The trailing unverified clause appears only when a
 * run left scenarios unscored — SPEC §4.9 ("unverified, never clean") and
 * §2.8's rule that an elision MUST leave a marker saying how much was cut,
 * which is the move §8.2 makes for a partial re-review. Without it a
 * cost-stopped run reads as a full pass.
 */
export function benchmarkSentence(facts) {
  const unverified = facts.unverifiedClause ? ` ${facts.unverifiedClause}` : '';
  return (
    `Planted-defect benchmark — regression corpus. On the ${facts.scenarios}-scenario committed corpus ` +
    `(${facts.model}, effort ${facts.effort}, recipe ${facts.recipeSha}, ${facts.invocation}), ` +
    `clud-bug caught ${facts.caught}/${facts.planted} planted defects (${facts.recallPct}%) and ` +
    `false-flagged ${facts.falsePositives} of ${facts.decoys} clean decoys. ` +
    `Run ${facts.runDate}: ${facts.costLine}.${unverified} ` +
    `This corpus is public and fixed, so the reviewer may have seen it — it measures regression, ` +
    `not liveness; SPEC 2.0 §8.2's generated planted-defect test is tracked separately. ` +
    `Per-defect table: benchmark/results/latest.json.`
  );
}

function replaceBlock(source, path, begin, end, body) {
  const from = source.indexOf(begin);
  const to = source.indexOf(end);
  if (from === -1 || to === -1 || to < from) {
    throw new Error(`${path} has no ${begin} … ${end} block`);
  }
  return source.slice(0, from + begin.length) + body + source.slice(to);
}

function markdownBody(facts) {
  const sentence = benchmarkSentence(facts);
  const lead = 'Planted-defect benchmark — regression corpus.';
  const caveat = facts.caveat ? `_${facts.caveat}_\n\n` : '';
  return `\n${GENERATED_NOTE}\n\n**${lead}** ${sentence.slice(lead.length + 1)}\n\n${caveat}`;
}

function siteConstBody(facts) {
  const entry = ([k, v]) => `  ${k}: ${typeof v === 'string' ? JSON.stringify(v) : v},`;
  return (
    '// Generated by scripts/render-benchmark.mjs from benchmark/results/latest.json.\n' +
    '// Do not edit by hand — `node scripts/check-benchmark-claims.mjs` fails CI on drift.\n' +
    '//\n' +
    '// Both benchmark passages on the site read every number from here, so the\n' +
    '// front page cannot claim a score the last run did not produce.\n' +
    '\n' +
    'export const BENCHMARK = {\n' +
    Object.entries(facts).map(entry).join('\n') +
    '\n} as const;\n' +
    '\n' +
    `export const BENCHMARK_SENTENCE =\n  ${JSON.stringify(benchmarkSentence(facts))};\n`
  );
}

/** Every published artifact, rendered in memory. path -> full file content. */
export function renderTargets(result) {
  const facts = benchmarkFacts(result);
  const rendered = new Map();
  for (const path of MARKDOWN_TARGETS) {
    const source = readFileSync(path, 'utf8');
    rendered.set(path, replaceBlock(source, path, BEGIN, END, markdownBody(facts)));
  }
  rendered.set(SITE_CONST, siteConstBody(facts));
  return rendered;
}

/**
 * The site pages are checked differently: they write their own prose around
 * the numbers rather than printing the sentence, so two rules hold them to the
 * result file.
 *
 * They carry no numerals at all inside their benchmark block, because every
 * one reads off `BENCHMARK` — a digit in there is a number that stopped
 * tracking the result file. And each block names the remainder, because a
 * block that can only render the ratio publishes a cost-stopped run as a full
 * pass: `BENCHMARK.unverified` (a count of its own) or
 * `BENCHMARK.unverifiedClause` (empty when there is no remainder) satisfies
 * it.
 *
 * A block that goes on to DESCRIBE the corpus is held to a third rule: it
 * reads the composition off the corpus fields. `BENCHMARK.planted` is planted-
 * scored, so "a committed corpus of 20 scenarios — 2 planted defects plus 1
 * clean look-alikes" is what a cost-stopped run published about a corpus that
 * holds fourteen and six.
 *
 * That third rule is keyed on the fact rendered, `BENCHMARK.scenarios` — the
 * corpus size — and not on the prose around it. A phrase match on "committed
 * corpus" is disarmed by a reword that keeps rendering the size (the fact the
 * rule exists to hold to the corpus fields) under different words; the fact
 * cannot be reworded out from under it.
 */
const REMAINDER_REFERENCE = /BENCHMARK\.unverified(Clause)?\b/;
const CORPUS_DESCRIPTION = /BENCHMARK\.scenarios\b/;
const CORPUS_REFERENCE = /BENCHMARK\.corpus(Planted|Decoys)\b/g;

export function jsxBlockViolations(targets = JSX_TARGETS) {
  const problems = [];
  for (const path of targets) {
    const source = readFileSync(path, 'utf8');
    const from = source.indexOf(JSX_BEGIN);
    const to = source.indexOf(JSX_END);
    if (from === -1 || to === -1 || to < from) {
      problems.push(`${path} has no ${JSX_BEGIN} … ${JSX_END} block`);
      continue;
    }
    if (!/from ['"][^'"]*lib\/benchmark-score['"]/.test(source)) {
      problems.push(`${path} does not import BENCHMARK from site/lib/benchmark-score`);
    }
    const region = source.slice(from + JSX_BEGIN.length, to);
    const digits = region.split('\n').flatMap((line, i) => (/\d/.test(line) ? [`  line ${i + 1}: ${line.trim()}`] : []));
    if (digits.length > 0) {
      problems.push(
        `${path}: the benchmark block carries a literal numeral; read it off BENCHMARK instead:\n${digits.join('\n')}`,
      );
    }
    if (!REMAINDER_REFERENCE.test(region)) {
      problems.push(
        `${path}: the benchmark block names no remainder — render BENCHMARK.unverifiedClause (or ` +
          `BENCHMARK.unverified) there, or a run that scored 8 scenarios of 20 publishes as a full pass`,
      );
    }
    if (CORPUS_DESCRIPTION.test(region) && new Set(region.match(CORPUS_REFERENCE) ?? []).size < 2) {
      problems.push(
        `${path}: the benchmark block describes the committed corpus but does not name its composition ` +
          `from the corpus — render BENCHMARK.corpusPlanted and BENCHMARK.corpusDecoys there, or a ` +
          `cost-stopped run publishes the fixed corpus as holding however many scenarios it reached`,
      );
    }
  }
  return problems;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = readLatest();
  for (const [path, content] of renderTargets(result)) {
    writeFileSync(path, content);
    console.log(`  rendered  ${path.slice(ROOT.length + 1)}`);
  }
  const problems = jsxBlockViolations();
  for (const problem of problems) console.error(`::error::render-benchmark: ${problem}`);
  if (problems.length > 0) process.exit(1);
  console.log(`\nrender-benchmark: ${benchmarkSentence(benchmarkFacts(result))}`);
}
